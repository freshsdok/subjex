const phraseBooks: Record<LanguageCode, PhraseBook> = { zh: zhPhrases, en: enPhrases };

export function pickLanguage(cookieValue: string | undefined): LanguageCode {
  return cookieValue === "en" ? "en" : "zh";
}

export function phrasesFor(language: LanguageCode): PhraseBook {
  return phraseBooks[language];
}

// Fills {name} placeholders — 替换文案里的 {占位符}。
export function fillPhrase(phrase: string, values: Record<string, string | number>): string {
  return phrase.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole));
}
